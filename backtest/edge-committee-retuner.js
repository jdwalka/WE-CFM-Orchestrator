#!/usr/bin/env node
// ================================================================
// WECRYPTO Edge Committee Retuner
//
// Out-of-the-box accuracy lift: selective voting by top-performing
// indicators instead of diluting edge across the full composite.
//
// Usage:
//   node backtest/edge-committee-retuner.js --days 11 --coins BTC,ETH,SOL,XRP
//   node backtest/edge-committee-retuner.js --days 11 --write-config
// ================================================================
'use strict';

const fs = require('fs');
const path = require('path');
const retuner = require('./outcome-retuner');
const committee = require('./edge-committee');

const {
  SYMBOL_MAP,
  generateWindows,
  fetchOutcome,
  fetchLookback,
  computeSignalVector,
  sleep,
} = retuner;

const { walkForwardValidate, buildCoinConfig, evaluateConfig, gradeIndicators, selectCommittee } = committee;

async function collectObservations(coin, windows, onProgress) {
  const sym = SYMBOL_MAP[coin];
  if (!sym) return [];

  const observations = [];
  let flat = 0;
  let errors = 0;
  let delayMs = 280;
  let errorStreak = 0;

  for (let i = 0; i < windows.length; i++) {
    if (onProgress && i > 0 && i % 50 === 0) onProgress(i, windows.length, observations.length, flat, errors);
    await sleep(delayMs);
    const outcome = await fetchOutcome(sym, windows[i].startMs);
    if (!outcome) {
      errors++;
      errorStreak++;
      if (errorStreak >= 5) delayMs = Math.min(2000, delayMs + 200);
      if (errorStreak >= 15) {
        console.log(`  [${coin}] Rate-limit backoff — sleeping 30s (${errorStreak} consecutive errors)`);
        await sleep(30000);
        delayMs = 500;
      }
      continue;
    }
    errorStreak = 0;
    delayMs = Math.max(280, delayMs - 20);
    if (outcome.direction === 'FLAT') { flat++; continue; }

    await sleep(delayMs);
    const candles = await fetchLookback(sym, windows[i].startMs);
    if (!candles || candles.length < 30) { errors++; continue; }

    const signalVector = computeSignalVector(candles);
    if (!signalVector) continue;

    observations.push({
      startMs: windows[i].startMs,
      actualDirection: outcome.direction,
      pct: outcome.pct,
      signalVector,
    });
  }

  if (onProgress) onProgress(windows.length, windows.length, observations.length, flat, errors);
  return { observations, flat, errors };
}

function loadExistingConfig(configPath) {
  if (!fs.existsSync(configPath)) return {};
  try {
    const src = fs.readFileSync(configPath, 'utf8');
    const match = src.match(/const EDGE_COMMITTEE_CONFIG = (\{[\s\S]*?\n\});/);
    if (!match) return {};
    // eslint-disable-next-line no-new-func
    return new Function(`return ${match[1]}`)();
  } catch (_) {
    return {};
  }
}

function writeLiveConfig(coinConfigs, outPath) {
  const stamp = new Date().toISOString().slice(0, 10);
  const body = `// Auto-generated by edge-committee-retuner on ${stamp}
// Selective indicator committee — only trade when top performers agree.
(function () {
  const EDGE_COMMITTEE_CONFIG = ${JSON.stringify(coinConfigs, null, 2)};

  function evaluate(signalVector, sym) {
    const coin = String(sym || '').toUpperCase();
    const cfg = EDGE_COMMITTEE_CONFIG[coin];
    if (!cfg || !cfg.enabled || !Array.isArray(cfg.committee) || !cfg.committee.length) {
      return { action: 'pass', reason: 'no_config' };
    }
    const members = cfg.committee.map((key) => ({
      key,
      winRate: cfg.memberWinRates?.[key] ?? 0.55,
    }));
    const vote = window.EdgeCommitteeCore?.committeeVote?.(signalVector, members, {
      minAgree: cfg.minAgree ?? 3,
      minStrength: cfg.minStrength ?? 0.22,
    });
    if (!vote) return { action: 'pass', reason: 'core_missing' };
    return vote;
  }

  function applyScoreGate(score, signalVector, sym) {
    const vote = evaluate(signalVector, sym);
    if (vote.action === 'abstain') {
      return { score: score * 0.35, gated: true, vote };
    }
    if (vote.action === 'trade') {
      const voteDir = vote.direction === 'UP' ? 1 : -1;
      const scoreDir = score > 0.08 ? 1 : score < -0.08 ? -1 : 0;
      if (scoreDir !== 0 && scoreDir !== voteDir) {
        return { score: score * 0.55, gated: true, vote, reason: 'committee_conflict' };
      }
      const boost = 1 + Math.min(0.18, (vote.strength || 0) * 0.25);
      return { score: score * boost, gated: false, vote };
    }
    return { score, gated: false, vote };
  }

  window.EdgeCommittee = {
    config: EDGE_COMMITTEE_CONFIG,
    evaluate,
    applyScoreGate,
  };
})();
`;

  fs.writeFileSync(outPath, body, 'utf8');
}

async function main() {
  const args = process.argv.slice(2);
  let days = 11;
  let coins = ['BTC', 'ETH', 'SOL', 'XRP'];
  let writeConfig = false;
  let mergeConfig = false;

  for (let i = 0; i < args.length; i++) {
    if (args[i] === '--days') days = parseFloat(args[++i]);
    else if (args[i] === '--coins') coins = args[++i].split(',');
    else if (args[i] === '--write-config') writeConfig = true;
    else if (args[i] === '--merge') mergeConfig = true;
  }

  const ROOT = path.resolve(__dirname, '..');
  const LOG_DIR = path.join(ROOT, 'backtest-logs');
  const CONFIG_OUT = path.join(ROOT, 'src', 'core', 'predictions', 'edge-committee-config.js');
  if (!fs.existsSync(LOG_DIR)) fs.mkdirSync(LOG_DIR, { recursive: true });

  const windows = generateWindows(days);
  const coinConfigs = {};
  const report = { timestamp: new Date().toISOString(), days, coins: {}, baseline: {} };

  console.log('\n' + '═'.repeat(72));
  console.log('WECRYPTO Edge Committee Retuner');
  console.log(`Days: ${days}  Coins: ${coins.join(',')}  WriteConfig: ${writeConfig}`);
  console.log('═'.repeat(72) + '\n');

  for (const coin of coins) {
    console.log(`\n── ${coin} — collecting ${windows.length} windows ──`);
    const { observations, flat, errors } = await collectObservations(coin, windows, (i, total, usable, f, e) => {
      console.log(`  Progress: ${i}/${total} — ${usable} usable, ${f} flat, ${e} errors`);
    });

    console.log(`  ${coin}: ${observations.length} directional windows (${flat} flat, ${errors} fetch errors)`);
    if (observations.length < 40) {
      console.log(`  SKIP ${coin}: insufficient observations`);
      continue;
    }

    const graded = gradeIndicators(observations);
    const top = graded.sort((a, b) => b.winRate - a.winRate).slice(0, 6);
    console.log(`  Top solo indicators: ${top.map((t) => `${t.key} ${(t.winRate * 100).toFixed(1)}%`).join(', ')}`);

    const fullCommittee = selectCommittee(graded, { minWinRate: 0.52, minSamples: 30, topK: 8 });
    const baseline = evaluateConfig(observations, fullCommittee, { minAgree: 2, minStrength: 0.15 });
    report.baseline[coin] = {
      winRate: +(baseline.winRate * 100).toFixed(1),
      coverage: +(baseline.coverage * 100).toFixed(1),
      trades: baseline.trades,
    };

    const wf = walkForwardValidate(observations);
    if (!wf) {
      console.log(`  SKIP ${coin}: walk-forward could not find viable committee`);
      continue;
    }

    const cfg = buildCoinConfig(wf);
    coinConfigs[coin] = cfg;
    report.coins[coin] = cfg;

    console.log(`\n  ${coin} COMMITTEE: [${wf.committee.map((m) => m.key).join(', ')}]`);
    console.log(`  Train: ${cfg.backtest.trainWinRate}% WR @ ${cfg.backtest.trainCoverage}% coverage (${wf.train.trades} trades)`);
    console.log(`  Test:  ${cfg.backtest.testWinRate}% WR @ ${cfg.backtest.testCoverage}% coverage (${wf.test.trades} trades)`);
    console.log(`  Gates: minAgree=${cfg.minAgree} minStrength=${cfg.minStrength} minWinRate=${cfg.minWinRate}`);
  }

  const stamp = new Date().toISOString().replace(/[:.]/g, '-').slice(0, 19);
  const jsonPath = path.join(LOG_DIR, `edge-committee-${stamp}.json`);
  fs.writeFileSync(jsonPath, JSON.stringify(report, null, 2), 'utf8');
  console.log(`\nReport: ${jsonPath}`);

  if (writeConfig && Object.keys(coinConfigs).length) {
    const merged = mergeConfig ? { ...loadExistingConfig(CONFIG_OUT), ...coinConfigs } : coinConfigs;
    writeLiveConfig(merged, CONFIG_OUT);
    console.log(`Live config: ${CONFIG_OUT}${mergeConfig ? ' (merged)' : ''}`);
    console.log('Load src/core/predictions/edge-committee-config.js in index.html before predictions.js');
  }

  console.log('\n' + '═'.repeat(72));
  console.log('DONE — trade less, agree more. Coverage drops; win rate should rise.');
  console.log('═'.repeat(72) + '\n');
}

if (require.main === module) {
  main().catch((e) => { console.error('FATAL:', e.stack); process.exit(1); });
}

module.exports = { collectObservations, writeLiveConfig };
